// sectionedRender is a mock-shaped render with a preamble and one section
// per part.
func sectionedRender(parts ...string) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by forge. DO NOT EDIT.\npackage p\n\n")
	for _, p := range parts {
		b.WriteString("// forge:section\n// Mock" + p + " mocks " + p + ".\ntype Mock" + p + " struct{}\n\n")
	}
	return []byte(b.String())
}

func TestStampSections_VerifyAndTamper(t *testing.T) {
	const rel = "internal/p/mock_gen.go"
	stamped, ok := Stamp(rel, sectionedRender("A", "B"))
	if !ok {
		t.Fatal("not stampable")
	}
	s := string(stamped)
	if got := strings.Count(s, "// forge:section forge:hash="); got != 2 {
		t.Fatalf("want 2 stamped section lines, got %d:\n%s", got, s)
	}
	if !strings.HasPrefix(s, "// Code generated by forge. DO NOT EDIT.\n// forge:hash=") {
		t.Fatalf("head marker misplaced:\n%s", s)
	}
	if Verify(stamped) != Pristine {
		t.Fatalf("stamped sectioned file must verify:\n%s", s)
	}
	if again, _ := Stamp(rel, stamped); string(again) != s {
		t.Errorf("Stamp is not idempotent:\n%s\n---\n%s", again, s)
	}
	// Body hash is the same for the render and its stamp.
	if BodyHash(stamped) != BodyHash(sectionedRender("A", "B")) {
		t.Error("BodyHash must not see section lines")
	}
	for name, edit := range map[string]func(string) string{
		"preamble": func(s string) string { return strings.Replace(s, "package p", "package q", 1) },
		"section": func(s string) string {
			return strings.Replace(s, "type MockB struct{}", "type MockB struct{ x int }", 1)
		},
		"unstamped section line": func(s string) string {
			i := strings.LastIndex(s, "// forge:section")
			j := strings.Index(s[i:], "\n")
			return s[:i] + "// forge:section" + s[i+j:]
		},
	} {
		if got := Verify([]byte(edit(s))); got != Modified {
			t.Errorf("%s edit: Verify = %v, want Modified", name, got)
		}
	}
	if Verify(StripMarker(stamped)) != NoMarker {
		t.Error("a disowned (stripped) sectioned file must carry no marker")
	}
}

// TestStampSections_PlainGitMergeOfIndependentParts is the property the
// sections exist for: two branches that change different parts of one
// generated file merge with plain git (no driver), and the merged file is
// byte-identical to a fresh stamp of the merged render — so it verifies.
func TestStampSections_PlainGitMergeOfIndependentParts(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	const rel = "mock_gen.go"
	render := func(a, c string, extra ...string) []byte {
		parts := append([]string{"A" + a, "B", "C" + c}, extra...)
		out, _ := Stamp(rel, sectionedRender(parts...))
		return out
	}
	dir := t.TempDir()
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.Command("git", append([]string{"-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false"}, args...)...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null")
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
		return string(out)
	}
	write := func(b []byte) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, rel), b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	git("init", "-q", "-b", "main")
	write(render("", ""))
	git("add", ".")
	git("commit", "-qm", "base")
	git("checkout", "-qb", "a")
	write(render("2", ""))
	git("commit", "-qam", "change A")
	git("checkout", "-q", "main")
	write(render("", "2"))
	git("commit", "-qam", "change C")
	git("merge", "-q", "--no-edit", "a")

	got, err := os.ReadFile(filepath.Join(dir, rel))
	if err != nil {
		t.Fatal(err)
	}
	if want := render("2", "2"); string(got) != string(want) {
		t.Fatalf("merged file differs from the render of the merged inputs:\n%s\n--- want ---\n%s", got, want)
	}
	if Verify(got) != Pristine {
		t.Error("the merged file must certify itself")
	}

	// A control: the same change without sections conflicts on the head
	// hash, which is the defect sections remove.
	if strings.Contains(string(got), "<<<<<<<") {
		t.Fatal("conflict markers in merged output")
	}
}
