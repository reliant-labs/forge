// TestStepAgentSkillsHarnessGate pins the delivery decision to the
// project's `harness:` setting: only claude has a native on-disk skills
// concept, so only claude gets files. Everything else — including the
// DEFAULT harness, reliant, which reads skills from the forge binary —
// gets nothing at all: no .claude/ directory, no writes recorded.
func TestStepAgentSkillsHarnessGate(t *testing.T) {
	for _, tc := range []struct {
		harness string
		deliver bool
	}{
		{string(generator.HarnessReliant), false},
		{string(generator.HarnessCursor), false},
		{string(generator.HarnessCopilot), false},
		{string(generator.HarnessCodex), false},
		{string(generator.HarnessClaude), true},
	} {
		t.Run(tc.harness, func(t *testing.T) {
			ctx := newSkillsPipelineCtxForHarness(t, tc.harness)
			if err := stepAgentSkills(ctx); err != nil {
				t.Fatalf("stepAgentSkills: %v", err)
			}
			_, err := os.Stat(filepath.Join(ctx.AbsPath, ".claude"))
			if tc.deliver {
				if err != nil {
					t.Fatalf("harness %q delivered nothing; want .claude/skills/: %v", tc.harness, err)
				}
				return
			}
			if !os.IsNotExist(err) {
				t.Errorf("harness %q wrote .claude/ (err=%v); want nothing written", tc.harness, err)
			}
			for rel := range checksums.WrittenThisRun {
				if strings.HasPrefix(rel, ".claude/") {
					t.Errorf("harness %q recorded a written skill path %q; want none", tc.harness, rel)
				}
			}
		})
	}
}

// TestStepAgentSkillsLegacyProjectKeepsDelivery covers the transition for
// projects that predate `harness:`. Those were all delivered
// .claude/skills/ unconditionally, and readers may depend on the files, so
// an ABSENT setting must not be read as the reliant default and start
// deleting. Absence means "carry on as before"; opting out is an explicit
// edit to forge.yaml.
func TestStepAgentSkillsLegacyProjectKeepsDelivery(t *testing.T) {
	ctx := newSkillsPipelineCtxForHarness(t, "")
	if err := stepAgentSkills(ctx); err != nil {
		t.Fatalf("stepAgentSkills: %v", err)
	}
	if _, err := os.Stat(filepath.Join(ctx.AbsPath, agentSkillRelPath(agentSkillsDir, "db"))); err != nil {
		t.Errorf("legacy project (no harness: key) lost its delivered skills: %v", err)
	}

	// A nil Cfg — the pipeline's directory-scan fallback, where no
	// forge.yaml was loaded at all — is the same unknown, same answer.
	ctx2 := newSkillsPipelineCtx(t)
	ctx2.Cfg = nil
	if err := stepAgentSkills(ctx2); err != nil {
		t.Fatalf("stepAgentSkills (nil cfg): %v", err)
	}
	if _, err := os.Stat(filepath.Join(ctx2.AbsPath, agentSkillRelPath(agentSkillsDir, "db"))); err != nil {
		t.Errorf("nil-config run lost its delivered skills: %v", err)
	}
}

// TestStepAgentSkillsSwitchToReliantWithdrawsDelivery covers the other
// half of the transition: a project that HAS delivered skills and then
// sets `harness: reliant` gets forge's own copies withdrawn (and the
// emptied directory pruned) rather than left to rot as 81 stale files
// forge no longer refreshes.
func TestStepAgentSkillsSwitchToReliantWithdrawsDelivery(t *testing.T) {
	ctx := newSkillsPipelineCtxForHarness(t, string(generator.HarnessClaude))
	if err := stepAgentSkills(ctx); err != nil {
		t.Fatalf("stepAgentSkills (claude): %v", err)
	}
	if _, err := os.Stat(filepath.Join(ctx.AbsPath, agentSkillRelPath(agentSkillsDir, "db"))); err != nil {
		t.Fatalf("precondition: claude delivery missing: %v", err)
	}

	ctx.Cfg.Harness = string(generator.HarnessReliant)
	if err := stepAgentSkills(ctx); err != nil {
		t.Fatalf("stepAgentSkills (reliant): %v", err)
	}
	if _, err := os.Stat(filepath.Join(ctx.AbsPath, ".claude")); !os.IsNotExist(err) {
		t.Errorf(".claude/ survived the switch to reliant (err=%v); want withdrawn", err)
	}
}

// TestStepAgentSkillsRetirementKeepsUserContent guards the withdrawal
// above from becoming destructive: a user's OWN skill directory, and a
// file whose forge marker no longer verifies (hand-edited), are kept —
// along with the .claude/ tree that holds them.
func TestStepAgentSkillsRetirementKeepsUserContent(t *testing.T) {
	ctx := newSkillsPipelineCtxForHarness(t, string(generator.HarnessClaude))
	if err := stepAgentSkills(ctx); err != nil {
		t.Fatalf("stepAgentSkills (claude): %v", err)
	}

	userSkill := filepath.Join(ctx.AbsPath, ".claude", "skills", "my-own-skill", "SKILL.md")
	if err := os.MkdirAll(filepath.Dir(userSkill), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(userSkill, []byte("# mine\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	edited := filepath.Join(ctx.AbsPath, agentSkillRelPath(agentSkillsDir, "db"))
	if err := os.WriteFile(edited, []byte("---\nname: db\n---\n<!-- forge:hash=deadbeef -->\nmy edits\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	ctx.Cfg.Harness = string(generator.HarnessReliant)
	if err := stepAgentSkills(ctx); err != nil {
		t.Fatalf("stepAgentSkills (reliant): %v", err)
	}
	if _, err := os.Stat(userSkill); err != nil {
		t.Errorf("user-authored skill deleted by harness switch: %v", err)
	}
	if _, err := os.Stat(edited); err != nil {
		t.Errorf("hand-edited skill deleted by harness switch: %v", err)
	}
}
