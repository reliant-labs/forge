package cli

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const tsPluginLockKey = "node_modules/" + frontendTSPluginPackage

// lockedTSPluginVersion returns the protoc-gen-es version a package-lock.json
// pins, or "" when the lockfile is absent or does not list the plugin.
func lockedTSPluginVersion(lockPath string) string {
	data, err := os.ReadFile(lockPath)
	if err != nil {
		return ""
	}
	var lock struct {
		Packages map[string]struct {
			Version string `json:"version"`
		} `json:"packages"`
	}
	if json.Unmarshal(data, &lock) != nil {
		return ""
	}
	return lock.Packages[tsPluginLockKey].Version
}

// installedTSPluginVersion reads the version of the protoc-gen-es package that
// sits in the node_modules holding pluginBin (…/node_modules/.bin/protoc-gen-es).
func installedTSPluginVersion(pluginBin string) string {
	nodeModules := filepath.Dir(filepath.Dir(pluginBin))
	data, err := os.ReadFile(filepath.Join(nodeModules, frontendTSPluginPackage, "package.json"))
	if err != nil {
		return ""
	}
	var pkg struct {
		Version string `json:"version"`
	}
	if json.Unmarshal(data, &pkg) != nil {
		return ""
	}
	return pkg.Version
}

// ensureTSPluginMatchesLock makes TypeScript generation independent of what
// happens to be installed on this machine.
//
// protoc-gen-es stamps its own version into every generated header
// ("@generated by protoc-gen-es vX.Y.Z"), and the output differs between
// versions. CI runs `npm ci`, which installs exactly what package-lock.json
// pins; a developer's node_modules can be older or newer than the lock, and
// then `forge generate` rewrites every stub with a header CI's regenerate
// reverts. So the lockfile is the pin: if the installed plugin differs, run
// `npm ci` to reconcile it, and fail loudly if it still differs.
//
// No lockfile (or no plugin entry in it) means there is nothing to pin to, and
// this does nothing. FORGE_SKIP_NPM_INSTALL turns the reconcile into an error
// rather than a silent pass.
func ensureTSPluginMatchesLock(feName, projectDir, feDir, pluginRel string) error {
	pluginAbs := filepath.Join(projectDir, filepath.FromSlash(strings.TrimPrefix(pluginRel, "./")))
	nodeModulesParent := filepath.Dir(filepath.Dir(filepath.Dir(pluginAbs)))

	var lockDir, want string
	for _, dir := range []string{nodeModulesParent, filepath.Join(projectDir, feDir), projectDir} {
		if v := lockedTSPluginVersion(filepath.Join(dir, "package-lock.json")); v != "" {
			lockDir, want = dir, v
			break
		}
	}
	if want == "" {
		return nil
	}

	got := installedTSPluginVersion(pluginAbs)
	if got == want {
		return nil
	}

	if os.Getenv("FORGE_SKIP_NPM_INSTALL") == "" {
		fmt.Printf("📦 %s: installed protoc-gen-es %s != package-lock.json %s — running `npm ci` so generated headers match CI\n",
			feName, orUnknown(got), want)
		cmd := exec.Command("npm", "ci", "--no-audit", "--no-fund")
		cmd.Dir = lockDir
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("%s: installed protoc-gen-es %s differs from package-lock.json %s and `npm ci` in %s failed: %w",
				feName, orUnknown(got), want, lockDir, err)
		}
		got = installedTSPluginVersion(pluginAbs)
		if got == want {
			return nil
		}
	}
	return fmt.Errorf("%s: installed protoc-gen-es %s does not match package-lock.json %s (%s). Generating with it would stamp a different "+
		"`@generated by protoc-gen-es` header than CI and rewrite every stub — run `npm ci` in %s",
		feName, orUnknown(got), want, filepath.Join(lockDir, "package-lock.json"), lockDir)
}

func orUnknown(v string) string {
	if v == "" {
		return "<unknown>"
	}
	return v
}
