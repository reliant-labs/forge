// fixtureManifest is a fixture-manifest_gen.ts as forge emits it, reduced to
// the lines that matter: a hash header, the seed fingerprints, and a body.
func fixtureManifest(hash, seed, files, body string) []byte {
	return []byte("// Code generated by forge. DO NOT EDIT.\n" +
		"// forge:hash=" + hash + "\n" +
		"//\n" +
		"export const SEED_FINGERPRINT = \"" + seed + "\";\n" +
		"export const SEED_CONFIG_FINGERPRINT = \"cfg-" + seed + "\";\n" +
		"export const SEED_FINGERPRINT_FILES = " + files + ";\n" +
		"\n" +
		body)
}

const fixtureBody = "export const tables = [\n  \"accounts\",\n  \"invoices\",\n  \"projects\",\n  \"users\",\n];\n" +
	"\n// unrelated\n// lines\n// between\n// the\n// two\n// edits\n" +
	"export const counts = {\n  accounts: 10,\n  users: 10,\n};\n"

// Two branches that each add a migration regenerate the fixture manifest: both
// change the hash header and the seed fingerprints, and they change the body
// in different places. Plain git conflicts on the fingerprint lines — the
// 2026-10-07 pin-PR conflicts. The driver merges the body and keeps this
// side's fingerprints for `forge generate` to refresh.
func TestMergeGenerated_FingerprintLinesNeverConflict(t *testing.T) {
	base := fixtureManifest("aaaa", "seed-base", "40", fixtureBody)
	ours := fixtureManifest("bbbb", "seed-ours", "41",
		strings.Replace(fixtureBody, "  \"accounts\",\n", "  \"accounts\",\n  \"coupons\",\n", 1))
	theirs := fixtureManifest("cccc", "seed-theirs", "41",
		strings.Replace(fixtureBody, "  users: 10,\n", "  users: 10,\n  webhooks: 10,\n", 1))

	// The baseline: git's own merge conflicts on the fingerprint lines.
	if plainGitMergeConflicts(t, base, ours, theirs) == 0 {
		t.Fatal("precondition: plain git merge-file should conflict on the fingerprint lines")
	}

	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil {
		t.Fatal(err)
	}
	if !clean {
		t.Fatalf("a merge that differs only in fingerprints and separate body hunks conflicted:\n%s", merged)
	}
	got := string(merged)
	for _, want := range []string{"\"coupons\",", "webhooks: 10,", "forge:hash=bbbb", "SEED_FINGERPRINT = \"seed-ours\"", "SEED_FINGERPRINT_FILES = 41;"} {
		if !strings.Contains(got, want) {
			t.Errorf("merged file lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, volatilePlaceholder) {
		t.Errorf("a placeholder leaked into the merge:\n%q", got)
	}
}

// A real conflict in the generated body is still a conflict.
func TestMergeGenerated_BodyConflictsStillConflict(t *testing.T) {
	base := fixtureManifest("aaaa", "s0", "1", fixtureBody)
	ours := fixtureManifest("bbbb", "s1", "1", strings.Replace(fixtureBody, "accounts: 10", "accounts: 20", 1))
	theirs := fixtureManifest("cccc", "s2", "1", strings.Replace(fixtureBody, "accounts: 10", "accounts: 30", 1))
	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil {
		t.Fatal(err)
	}
	if clean || !strings.Contains(string(merged), "<<<<<<< ours") {
		t.Fatalf("a body conflict was reported clean:\n%s", merged)
	}
}

// gen/forge_descriptor.json's source_hash is a digest of every .proto, so any
// two proto-changing branches change it.
func TestMergeGenerated_DescriptorSourceHash(t *testing.T) {
	desc := func(hash, field string) []byte {
		return []byte("{\n  \"source_hash\": \"" + hash + "\",\n  \"services\": [\n    \"a\",\n    \"b\",\n    \"c\",\n    \"d\",\n    \"e\"" + field + "\n  ]\n}\n")
	}
	base := desc("h0", "")
	ours := []byte(strings.Replace(string(desc("h1", "")), "    \"a\",\n", "    \"a\",\n    \"a2\",\n", 1))
	theirs := desc("h2", ",\n    \"f\"")
	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil || !clean {
		t.Fatalf("clean=%v err=%v:\n%s", clean, err, merged)
	}
	if !strings.Contains(string(merged), `"source_hash": "h1"`) || !strings.Contains(string(merged), `"a2"`) || !strings.Contains(string(merged), `"f"`) {
		t.Errorf("merged descriptor:\n%s", merged)
	}
}

// stampedRender is a Tier-1 file as forge writes it: the body certified by a
// real forge:hash marker, so checksums.Verify answers Pristine.
func stampedRender(t *testing.T, relPath string, body []byte) []byte {
	t.Helper()
	out, ok := checksums.Stamp(relPath, body)
	if !ok {
		t.Fatalf("%s is not stampable", relPath)
	}
	if checksums.Verify(out) != checksums.Pristine {
		t.Fatalf("precondition: a fresh stamp should verify Pristine")
	}
	return out
}

// Two pristine renders whose bodies changed in different places merge into a
// body neither side's marker certifies. Keeping ours' marker made the merged
// file verify Modified, so the next `forge generate` refused it as a hand-edit
// instead of refreshing it. A clean merge of two pristine renders holds no
// human edit, so it is certified as a render of some vintage — which the next
// generate overwrites.
func TestMergeGenerated_PristineSidesMergeIntoAPristineFile(t *testing.T) {
	const relPath = "frontends/web/src/mocks/fixture-manifest_gen.ts"
	body := func(seed, b string) []byte {
		raw := string(fixtureManifest("x", seed, "40", b))
		return []byte(strings.Replace(raw, "// forge:hash=x\n", "", 1))
	}
	base := stampedRender(t, relPath, body("seed-base", fixtureBody))
	ours := stampedRender(t, relPath, body("seed-ours",
		strings.Replace(fixtureBody, "  \"accounts\",\n", "  \"accounts\",\n  \"coupons\",\n", 1)))
	theirs := stampedRender(t, relPath, body("seed-theirs",
		strings.Replace(fixtureBody, "  users: 10,\n", "  users: 10,\n  webhooks: 10,\n", 1)))

	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil || !clean {
		t.Fatalf("clean=%v err=%v:\n%s", clean, err, merged)
	}
	if got := checksums.Verify(merged); got != checksums.Pristine {
		t.Fatalf("merged file verifies %v, want Pristine — forge generate would refuse it as hand-edited:\n%s", got, merged)
	}
	if !strings.Contains(string(merged), "\"coupons\",") || !strings.Contains(string(merged), "webhooks: 10,") {
		t.Errorf("merged body lost a side:\n%s", merged)
	}
}

// A side that was hand-edited is never laundered into a pristine file: forge
// would then overwrite the hand-edit without asking.
func TestMergeGenerated_HandEditedSideStaysModified(t *testing.T) {
	const relPath = "internal/app/thing_gen.go"
	base := stampedRender(t, relPath, []byte("// Code generated by forge. DO NOT EDIT.\npackage app\n\nconst A = 1\n\n// gap\n// gap\n// gap\n\nconst B = 2\n"))
	ours := stampedRender(t, relPath, []byte("// Code generated by forge. DO NOT EDIT.\npackage app\n\nconst A = 10\n\n// gap\n// gap\n// gap\n\nconst B = 2\n"))
	// theirs: a forge render, then a hand edit to the body under the marker.
	theirs := []byte(strings.Replace(string(base), "const B = 2", "const B = 2 // hand edit", 1))
	if checksums.Verify(theirs) != checksums.Modified {
		t.Fatal("precondition: theirs should verify Modified")
	}

	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil || !clean {
		t.Fatalf("clean=%v err=%v:\n%s", clean, err, merged)
	}
	if !strings.Contains(string(merged), "// hand edit") {
		t.Fatalf("merge lost the hand edit:\n%s", merged)
	}
	if got := checksums.Verify(merged); got == checksums.Pristine {
		t.Fatalf("a hand edit was certified Pristine; forge generate would overwrite it silently:\n%s", merged)
	}
}

// The scaffold declares the driver for forge's generated files.
func TestGitattributesTemplateDeclaresTheDriver(t *testing.T) {
	b, err := os.ReadFile(filepath.Join("..", "templates", "project", ".gitattributes"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"*_gen.ts merge=forge-generated", "forge_descriptor.json merge=forge-generated"} {
		if !strings.Contains(string(b), want) {
			t.Errorf(".gitattributes template lacks %q", want)
		}
	}
}

func plainGitMergeConflicts(t *testing.T, base, ours, theirs []byte) int {
	t.Helper()
	dir := t.TempDir()
	for name, body := range map[string][]byte{"base": base, "ours": ours, "theirs": theirs} {
		if err := os.WriteFile(filepath.Join(dir, name), body, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	err := exec.Command("git", "merge-file", "-p", filepath.Join(dir, "ours"), filepath.Join(dir, "base"), filepath.Join(dir, "theirs")).Run()
	if exitErr, ok := err.(*exec.ExitError); ok {
		return exitErr.ExitCode()
	}
	return 0
}
