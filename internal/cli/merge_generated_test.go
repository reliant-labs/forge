// fixtureManifest is a fixture-manifest_gen.ts as forge emits it, reduced to
// the lines that matter: a hash header, the seed fingerprints, and a body.
func fixtureManifest(hash, seed, files, body string) []byte {
	return []byte("// Code generated by forge. DO NOT EDIT.\n" +
		"// forge:hash=" + hash + "\n" +
		"//\n" +
		"export const SEED_FINGERPRINT = \"" + seed + "\";\n" +
		"export const SEED_CONFIG_FINGERPRINT = \"cfg-" + seed + "\";\n" +
		"export const SEED_FINGERPRINT_FILES = " + files + ";\n" +
		"\n" +
		body)
}

const fixtureBody = "export const tables = [\n  \"accounts\",\n  \"invoices\",\n  \"projects\",\n  \"users\",\n];\n" +
	"\n// unrelated\n// lines\n// between\n// the\n// two\n// edits\n" +
	"export const counts = {\n  accounts: 10,\n  users: 10,\n};\n"

// Two branches that each add a migration regenerate the fixture manifest: both
// change the hash header and the seed fingerprints, and they change the body
// in different places. Plain git conflicts on the fingerprint lines — the
// 2026-10-07 pin-PR conflicts. The driver merges the body and keeps this
// side's fingerprints for `forge generate` to refresh.
func TestMergeGenerated_FingerprintLinesNeverConflict(t *testing.T) {
	base := fixtureManifest("aaaa", "seed-base", "40", fixtureBody)
	ours := fixtureManifest("bbbb", "seed-ours", "41",
		strings.Replace(fixtureBody, "  \"accounts\",\n", "  \"accounts\",\n  \"coupons\",\n", 1))
	theirs := fixtureManifest("cccc", "seed-theirs", "41",
		strings.Replace(fixtureBody, "  users: 10,\n", "  users: 10,\n  webhooks: 10,\n", 1))

	// The baseline: git's own merge conflicts on the fingerprint lines.
	if plainGitMergeConflicts(t, base, ours, theirs) == 0 {
		t.Fatal("precondition: plain git merge-file should conflict on the fingerprint lines")
	}

	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil {
		t.Fatal(err)
	}
	if !clean {
		t.Fatalf("a merge that differs only in fingerprints and separate body hunks conflicted:\n%s", merged)
	}
	got := string(merged)
	for _, want := range []string{"\"coupons\",", "webhooks: 10,", "forge:hash=bbbb", "SEED_FINGERPRINT = \"seed-ours\"", "SEED_FINGERPRINT_FILES = 41;"} {
		if !strings.Contains(got, want) {
			t.Errorf("merged file lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, volatilePlaceholder) {
		t.Errorf("a placeholder leaked into the merge:\n%q", got)
	}
}

// A real conflict in the generated body is still a conflict.
func TestMergeGenerated_BodyConflictsStillConflict(t *testing.T) {
	base := fixtureManifest("aaaa", "s0", "1", fixtureBody)
	ours := fixtureManifest("bbbb", "s1", "1", strings.Replace(fixtureBody, "accounts: 10", "accounts: 20", 1))
	theirs := fixtureManifest("cccc", "s2", "1", strings.Replace(fixtureBody, "accounts: 10", "accounts: 30", 1))
	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil {
		t.Fatal(err)
	}
	if clean || !strings.Contains(string(merged), "<<<<<<< ours") {
		t.Fatalf("a body conflict was reported clean:\n%s", merged)
	}
}

// descriptorJSON renders a descriptor the way forge's writer does
// (json.MarshalIndent of codegen.ForgeDescriptor), with the given services
// and per-proto fingerprints.
func descriptorJSON(t *testing.T, services []string, sources map[string]string) []byte {
	t.Helper()
	out, err := json.MarshalIndent(struct {
		Services []string          `json:"services"`
		Configs  []string          `json:"configs"`
		Sources  map[string]string `json:"sources,omitempty"`
	}{services, nil, sources}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(out, '\n')
}

// gen/forge_descriptor.json stamps the protos it came from, one fingerprint
// per proto. Two branches that edit DIFFERENT protos each change the stamp; the
// merge must carry both edits, so the merged stamp is what a generate over the
// merged protos writes and nothing needs regenerating or amending.
func TestMergeDescriptor_DisjointProtoEditsMergeKeyByKey(t *testing.T) {
	svcs := []string{"a", "b", "c", "d", "e", "f", "g", "h"}
	base := descriptorJSON(t, svcs, map[string]string{"proto/a.proto": "a0", "proto/b.proto": "b0", "proto/c.proto": "c0"})
	// ours edits a.proto and adds a service at the top; theirs edits b.proto,
	// adds a proto, and adds a service at the bottom.
	ours := descriptorJSON(t, append([]string{"a2"}, svcs...), map[string]string{"proto/a.proto": "a1", "proto/b.proto": "b0", "proto/c.proto": "c0"})
	theirs := descriptorJSON(t, append(append([]string{}, svcs...), "z"), map[string]string{"proto/a.proto": "a0", "proto/b.proto": "b1", "proto/c.proto": "c0", "proto/d.proto": "d1"})

	got, clean, ok, err := mergeDescriptor(context.Background(), base, ours, theirs, 7)
	if err != nil || !ok || !clean {
		t.Fatalf("clean=%v ok=%v err=%v:\n%s", clean, ok, err, got)
	}
	want := descriptorJSON(t, append(append([]string{"a2"}, svcs...), "z"),
		map[string]string{"proto/a.proto": "a1", "proto/b.proto": "b1", "proto/c.proto": "c0", "proto/d.proto": "d1"})
	if string(got) != string(want) {
		t.Errorf("merged descriptor is not what a generate over both sides writes:\n--- got\n%s--- want\n%s", got, want)
	}
}

