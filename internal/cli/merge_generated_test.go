// stampedRender is a Tier-1 file as forge writes it: the body certified by a
// real forge:hash marker, so checksums.Verify answers Pristine.
func stampedRender(t *testing.T, relPath string, body []byte) []byte {
	t.Helper()
	out, ok := checksums.Stamp(relPath, body)
	if !ok {
		t.Fatalf("%s is not stampable", relPath)
	}
	if checksums.Verify(out) != checksums.Pristine {
		t.Fatalf("precondition: a fresh stamp should verify Pristine")
	}
	return out
}

// Two pristine renders whose bodies changed in different places merge into a
// body neither side's marker certifies. Keeping ours' marker made the merged
// file verify Modified, so the next `forge generate` refused it as a hand-edit
// instead of refreshing it. A clean merge of two pristine renders holds no
// human edit, so it is certified as a render of some vintage — which the next
// generate overwrites.
func TestMergeGenerated_PristineSidesMergeIntoAPristineFile(t *testing.T) {
	const relPath = "frontends/web/src/mocks/fixture-manifest_gen.ts"
	body := func(seed, b string) []byte {
		raw := string(fixtureManifest("x", seed, "40", b))
		return []byte(strings.Replace(raw, "// forge:hash=x\n", "", 1))
	}
	base := stampedRender(t, relPath, body("seed-base", fixtureBody))
	ours := stampedRender(t, relPath, body("seed-ours",
		strings.Replace(fixtureBody, "  \"accounts\",\n", "  \"accounts\",\n  \"coupons\",\n", 1)))
	theirs := stampedRender(t, relPath, body("seed-theirs",
		strings.Replace(fixtureBody, "  users: 10,\n", "  users: 10,\n  webhooks: 10,\n", 1)))

	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil || !clean {
		t.Fatalf("clean=%v err=%v:\n%s", clean, err, merged)
	}
	if got := checksums.Verify(merged); got != checksums.Pristine {
		t.Fatalf("merged file verifies %v, want Pristine — forge generate would refuse it as hand-edited:\n%s", got, merged)
	}
	if !strings.Contains(string(merged), "\"coupons\",") || !strings.Contains(string(merged), "webhooks: 10,") {
		t.Errorf("merged body lost a side:\n%s", merged)
	}
}

// A side that was hand-edited is never laundered into a pristine file: forge
// would then overwrite the hand-edit without asking.
func TestMergeGenerated_HandEditedSideStaysModified(t *testing.T) {
	const relPath = "internal/app/thing_gen.go"
	base := stampedRender(t, relPath, []byte("// Code generated by forge. DO NOT EDIT.\npackage app\n\nconst A = 1\n\n// gap\n// gap\n// gap\n\nconst B = 2\n"))
	ours := stampedRender(t, relPath, []byte("// Code generated by forge. DO NOT EDIT.\npackage app\n\nconst A = 10\n\n// gap\n// gap\n// gap\n\nconst B = 2\n"))
	// theirs: a forge render, then a hand edit to the body under the marker.
	theirs := []byte(strings.Replace(string(base), "const B = 2", "const B = 2 // hand edit", 1))
	if checksums.Verify(theirs) != checksums.Modified {
		t.Fatal("precondition: theirs should verify Modified")
	}

	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil || !clean {
		t.Fatalf("clean=%v err=%v:\n%s", clean, err, merged)
	}
	if !strings.Contains(string(merged), "// hand edit") {
		t.Fatalf("merge lost the hand edit:\n%s", merged)
	}
	if got := checksums.Verify(merged); got == checksums.Pristine {
		t.Fatalf("a hand edit was certified Pristine; forge generate would overwrite it silently:\n%s", merged)
	}
}

