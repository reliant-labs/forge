// An all-annotated config project must still get a Go surface
// (fr-config-all-binary).
//
// Per-binary config arrived as a message-level (forge.v1.binary_config)
// annotation. A project that annotates EVERY config message — no unannotated
// root AppConfig left — is the natural end state of that migration, but it
// used to collapse the Go half silently: BuildConfigTemplateData skips
// binary-bound messages when collecting root fields, so data.Fields came back
// empty, and GenerateConfigLoader early-returned on that. Forge emitted the
// per-binary KCL and left pkg/config/config_gen.go STALE — the old content
// from before the migration, or nothing at all.
//
// Silence is the worst outcome forge can produce, so these tests pin the
// chosen semantics: an all-annotated project is LEGITIMATE, and forge emits a
// per-binary Go surface for each annotated message with no root Config type.
package codegen

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// allBinaryMessages is the all-annotated shape: a shared BaseConfig
// DEFINITION plus two binary-bound messages, and NO unannotated root.
// It is named separately from perBinaryMessages (which it reuses) because
// the property under test is what that fixture does NOT contain: no message
// is an unannotated root, since BaseConfig is reachable only through
// composition.
func allBinaryMessages() []ConfigMessage { return perBinaryMessages() }

// The reproduction: with every message binary-annotated, the root field
// collection is empty by design, and that must NOT be read as "nothing to
// generate".
func TestBuildConfigTemplateData_AllBinaryAnnotated_HasNoRootButHasBinaries(t *testing.T) {
	data := BuildConfigTemplateData(allBinaryMessages())

	if data.RootConfigMessage != "" {
		t.Errorf("RootConfigMessage = %q, want empty: no message is an unannotated root", data.RootConfigMessage)
	}
	if len(data.Fields) != 0 {
		t.Errorf("Fields = %d, want 0: every field belongs to a binary", len(data.Fields))
	}
	if len(data.BinaryConfigs) != 2 {
		t.Fatalf("BinaryConfigs = %d, want 2 — the Go surface forge must still emit", len(data.BinaryConfigs))
	}
}

// The bug itself: forge must not leave pkg/config/config_gen.go stale when
// every config message is binary-bound.
func TestGenerateConfigLoader_AllBinaryAnnotated_EmitsPerBinarySurface(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/proj\n\ngo 1.24\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	genPath := filepath.Join(dir, "pkg", "config", "config_gen.go")
	if err := os.MkdirAll(filepath.Dir(genPath), 0o755); err != nil {
		t.Fatal(err)
	}
	// Seed the STALE file a real migration would have on disk: the surface
	// from before any message was annotated.
	const stale = "// Code generated by forge. DO NOT EDIT.\npackage config\n\n// stale: pre-migration root surface\ntype Config = int\n"
	if err := os.WriteFile(genPath, []byte(stale), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := GenerateConfigLoader(allBinaryMessages(), dir, nil); err != nil {
		t.Fatalf("GenerateConfigLoader: %v", err)
	}

	got, err := os.ReadFile(genPath)
	if err != nil {
		t.Fatalf("read config_gen.go: %v", err)
	}
	src := string(got)

	if strings.Contains(src, "stale: pre-migration root surface") {
		t.Fatal("SILENT STALE FILE: forge left the pre-migration pkg/config/config_gen.go untouched " +
			"while emitting per-binary KCL — the Go half of the project has no valid config surface")
	}

	// It must parse: a half-rendered or empty file is just a louder silence.
	if _, perr := parser.ParseFile(token.NewFileSet(), genPath, got, parser.AllErrors); perr != nil {
		t.Fatalf("generated config_gen.go does not parse: %v\n---\n%s", perr, src)
	}

	// Each binary gets its own type + loader.
	for _, want := range []string{
		"type AdminConfig = configv1.AdminConfig",
		"func LoadAdminConfig(",
		"func RegisterAdminConfigFlags(",
		"type GatewayConfig = configv1.GatewayConfig",
		"func LoadGatewayConfig(",
		"func RegisterGatewayConfigFlags(",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated config_gen.go missing %q", want)
		}
	}

	// And NO root Config alias: there is no unannotated message to alias, so
	// emitting one would name a proto type that does not exist.
	if strings.Contains(src, "type Config = configv1.") {
		t.Error("emitted a root Config alias for a project that has no unannotated root message")
	}
	if strings.Contains(src, "func Load(cmd") {
		t.Error("emitted the root Load() for a project with no root config message")
	}
}

// A project with NO config messages at all is a different case and must stay
// a no-op: there is nothing to describe, so writing an empty shim would be
// noise (and would break the scaffold path that generates before any proto).
func TestGenerateConfigLoader_NoMessages_StaysNoOp(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/proj\n\ngo 1.24\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := GenerateConfigLoader(nil, dir, nil); err != nil {
		t.Fatalf("GenerateConfigLoader: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "pkg", "config", "config_gen.go")); !os.IsNotExist(err) {
		t.Errorf("a project with no config messages must not get a config_gen.go (stat err = %v)", err)
	}
}
