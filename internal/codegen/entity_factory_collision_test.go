// Report a640ad4c: CRUD-shaped reads claim Deployment even though its handler
// already declares a production constructor named NewDeployment. Use an isolated
// applied-schema fixture, never the live control-plane checkout.
func TestEntityFactories_OwnedDeclarations(t *testing.T) {
	for _, tc := range []struct {
		name, file, source    string
		conflict, wantFactory bool
	}{
		{name: "production constructor", file: "service.go", source: "package orders\nfunc NewDeployment() {}\n"},
		{name: "in-package test factory", file: "factory_test.go", source: "package orders\nfunc NewDeployment() {}\n"},
		{name: "external test is separate", file: "external_test.go", source: "package orders_test\nfunc NewDeployment() {}\n", wantFactory: true},
		{name: "method is separate", file: "method.go", source: "package orders\ntype Service struct{}\nfunc (*Service) NewDeployment() {}\n", wantFactory: true},
		{name: "previous output is not ownership", file: entityFactoryFile, source: "// Code generated by forge. DO NOT EDIT.\npackage orders\nfunc NewDeployment() {}\n", wantFactory: true},
		{name: "override type conflict", file: "override_test.go", source: "package orders\ntype DeploymentOverride string\n", conflict: true},
		{name: "shared helper conflict", file: "helper_test.go", source: "package orders\nfunc seedFactoryParents() {}\n", conflict: true},
		{name: "SQL constant conflict", file: "sql_test.go", source: "package orders\nconst deploymentFactoryRootSQL = \"owned\"\n", conflict: true},
		{name: "factory variable conflict", file: "var_test.go", source: "package orders\nvar NewDeployment = 1\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			project, dir := writeHandlerFiles(t, map[string]string{"service.go": "package orders\n", tc.file: tc.source})
			stubFactorySchema(t, project)
			svc := ServiceDef{Name: "OrdersService", Methods: []Method{{Name: "GetDeployment"}, {Name: "ListDeployments"}, {Name: "GetWidget"}}}
			err := GenerateEntityFactories(project, "example.com/test", []ServiceDef{svc}, nil)
			if tc.conflict {
				if err == nil || !strings.Contains(err.Error(), tc.file) {
					t.Fatalf("want actionable declaration conflict naming %s, got %v", tc.file, err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			out, err := os.ReadFile(filepath.Join(dir, entityFactoryFile))
			if err != nil {
				t.Fatal(err)
			}
			if got := strings.Contains(string(out), "func NewDeployment("); got != tc.wantFactory {
				t.Errorf("NewDeployment emitted = %v, want %v", got, tc.wantFactory)
			}
			if !strings.Contains(string(out), "func NewWidget(") {
				t.Error("unrelated factory was suppressed")
			}
			if !tc.wantFactory && !strings.Contains(string(out), "func ForgeNewDeployment(") {
				t.Error("occupied factory name must get a deterministic fallback, not be omitted")
			}
			// Generation must converge, not mistake its own previous output for ownership.
			if err := GenerateEntityFactories(project, "example.com/test", []ServiceDef{svc}, nil); err != nil {
				t.Fatal(err)
			}
			again, err := os.ReadFile(filepath.Join(dir, entityFactoryFile))
			if err != nil {
				t.Fatal(err)
			}
			if string(out) != string(again) {
				t.Error("factory emission is not idempotent")
			}
			got, err := os.ReadFile(filepath.Join(dir, tc.file))
			if err != nil {
				t.Fatal(err)
			}
			if tc.file != entityFactoryFile && string(got) != tc.source {
				t.Error("owned file changed")
			}
		})
	}
}

func stubFactorySchema(t *testing.T, project string) {
	t.Helper()
	var tables []schemadef.Table
	for _, name := range []string{"deployments", "widgets"} {
		tables = append(tables, schemadef.Table{Name: name, PKCols: []string{"id"}, Columns: []schemadef.Column{{Name: "id", Type: schemadef.TypeString, NotNull: true, IsPK: true}}})
	}
	orig := openAppliedSchema
	openAppliedSchema = func(string, string) ([]schemadef.Table, *schemadef.Shadow, error) { return tables, nil, nil }
	t.Cleanup(func() { openAppliedSchema = orig })
	dir := filepath.Join(project, "internal", "db")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	src := "package db\n" + "type Deployment struct { bun.BaseModel `bun:\"table:deployments\"`; Id string `bun:\"id,pk\"` }\n" + "type Widget struct { bun.BaseModel `bun:\"table:widgets\"`; Id string `bun:\"id,pk\"` }\n"
	if err := os.WriteFile(filepath.Join(dir, "entities.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestEntityFactories_OwnedRequestFactory(t *testing.T) {
	mine := "package orders\nfunc NewCreateWidgetRequest() {}\n"
	project, dir := writeHandlerFiles(t, map[string]string{"service.go": "package orders\n", "factory_test.go": mine})
	stubFactorySchema(t, project)
	svc := ServiceDef{Name: "OrdersService", GoPackage: "example.com/test/pb", Methods: []Method{{Name: "CreateWidget", InputType: "CreateWidgetRequest", OutputType: "CreateWidgetResponse"}}, Messages: map[string][]MessageFieldDef{"Widget": {{Name: "id", ProtoType: "string"}}, "CreateWidgetRequest": {}}}
	if err := GenerateEntityFactories(project, "example.com/test", []ServiceDef{svc}, nil); err != nil {
		t.Fatal(err)
	}
	out, err := os.ReadFile(filepath.Join(dir, entityFactoryFile))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(out), "func NewCreateWidgetRequest(") {
		t.Error("generated request factory redeclares user-owned test helper")
	}
	if !strings.Contains(string(out), "func NewWidget(") || !strings.Contains(string(out), "func ForgeNewCreateWidgetRequest(") {
		t.Error("occupied request name must not suppress either factory")
	}
}

// Type-check the actual rendered file without a subprocess, network or live DB.
// Minimal dependency packages expose only the APIs these factories consume.
func checkFactoryTypes(t *testing.T, out []byte, owned ...string) {
	t.Helper()
	fset := token.NewFileSet()
	pkgs := map[string]*types.Package{}
	imp := importerFunc(func(path string) (*types.Package, error) { return pkgs[path], nil })
	for _, stub := range []struct{ path, src string }{
		{"context", "package context; type Context interface{}; func Background() Context { return nil }"},
		{"testing", "package testing; type TB interface { Helper(); Fatalf(string,...any) }"},
		{"strings", "package strings; func ReplaceAll(s,old,new string) string {return s}; type Builder struct{}; func (*Builder) WriteString(string)(int,error){return 0,nil}; func (*Builder) String()string{return \"\"}"},
		{"github.com/reliant-labs/forge/pkg/orm", "package orm; import \"context\"; type Context interface { Exec(context.Context,string,...any)(any,error) }"},
		{"github.com/oklog/ulid/v2", "package ulid; type ULID struct{}; func Make() ULID{return ULID{}}; func (ULID) String()string{return \"id\"}"},
		{"example.com/test/pb", "package pb; type CreateWidgetRequest struct{}; type CreateTenantRequest struct{}"},
		{"example.com/test/internal/db", "package db; import \"context\"; import \"github.com/reliant-labs/forge/pkg/orm\"; type Widget struct{}; type Deployment struct{}; func GetDeploymentByID(context.Context,orm.Context,string)(*Deployment,error){return nil,nil}; func UpdateDeployment(context.Context,orm.Context,*Deployment)error{return nil}; func GetWidgetByID(context.Context,orm.Context,string)(*Widget,error){return nil,nil}; func UpdateWidget(context.Context,orm.Context,*Widget)error{return nil}"},
	} {
		f, err := parser.ParseFile(fset, stub.path, stub.src, 0)
		if err != nil {
			t.Fatal(err)
		}
		pkg, err := (&types.Config{Importer: imp}).Check(stub.path, fset, []*ast.File{f}, nil)
		if err != nil {
			t.Fatal(err)
		}
		pkgs[stub.path] = pkg
	}
	f, err := parser.ParseFile(fset, entityFactoryFile, out, 0)
	if err != nil {
		t.Fatal(err)
	}
	files := []*ast.File{f}
	for _, src := range owned {
		file, err := parser.ParseFile(fset, "owned.go", src, 0)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, file)
	}
	if _, err := (&types.Config{Importer: imp}).Check("example.com/test/internal/handlers/orders", fset, files, nil); err != nil {
		t.Fatalf("rendered factory does not type-check: %v\n%s", err, out)
	}
}

func TestEntityFactories_FailingSpecsTypeCheck(t *testing.T) {
	for _, mixed := range []bool{false, true} {
		t.Run(map[bool]string{false: "all failing", true: "mixed"}[mixed], func(t *testing.T) {
			const failure = "constraint widgets_parent_owner_check rejects every planned row"
			g := factoryGroup{pkg: "orders", pbImport: "example.com/test/pb", creates: []createRequestSpec{{funcName: "NewCreateWidgetRequest", inputType: "CreateWidgetRequest", entity: "Widget", ownerAware: true, failure: failure}}}
			if mixed {
				g.creates = append(g.creates, createRequestSpec{funcName: "NewCreateTenantRequest", inputType: "CreateTenantRequest", entity: "Tenant", ownerAware: true})
			}
			out := renderEntityFactoryFile("example.com/test/internal/db", g)
			for _, want := range []string{"opts ...FactoryOption", "type FactoryOption", "func FactoryOwner(", "t.Fatalf(\"NewCreateWidgetRequest: forge could not derive a request", failure} {
				if !strings.Contains(string(out), want) {
					t.Fatalf("failing factory lost %q", want)
				}
			}
			checkFactoryTypes(t, out)
		})
	}
	t.Run("failing row", func(t *testing.T) {
		out := renderEntityFactoryFile("example.com/test/internal/db", factoryGroup{pkg: "orders", specs: []entityFactorySpec{{goName: "Widget", lower: "widget", failure: "postgres refused row"}}})
		if !strings.Contains(string(out), "postgres refused row") || !strings.Contains(string(out), "t.Fatalf(") {
			t.Error("row diagnostic suppressed")
		}
		if strings.Contains(string(out), `"github.com/oklog/ulid/v2"`) {
			t.Fatal("failure-only row factories must not import the unused ID generator")
		}
		checkFactoryTypes(t, out)
	})
}
