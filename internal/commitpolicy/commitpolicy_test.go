// preFixScaffoldGitignore is the generated-code section of the scaffold
// .gitignore every forge project was born with before generated code became
// committed — verbatim in effect. A project keeps its .gitignore forever, so
// this is the state the check exists to catch.
const preFixScaffoldGitignore = `bin/
gen/*
!gen/go.mod
!gen/go.sum
handlers/**/*_gen.go
pkg/middleware/*_gen.go
/mocks/
/handlers/mocks/
`

const forgeBanner = "// Code generated by forge. DO NOT EDIT.\n// forge:hash=0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef\n"

func git(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-C", dir}, args...)...)
	cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@t", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@t")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return string(out)
}

func write(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func newRepo(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	dir := t.TempDir()
	git(t, dir, "init", "-q")
	return dir
}

// seedGenerated writes the files a forge project's generate produces.
func seedGenerated(t *testing.T, dir string) {
	t.Helper()
	write(t, dir, "gen/go.mod", "module example.com/x/gen\n")
	write(t, dir, "gen/services/api/v1/api.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage apiv1\n")
	write(t, dir, "gen/forge_descriptor.json", "{}\n")
	write(t, dir, "pkg/middleware/procedures_gen.go", forgeBanner+"package middleware\n")
	// handlers/**/*_gen.go is anchored (it contains a slash), so the old rule
	// ignored the legacy top-level handlers/ tree but never internal/handlers/.
	write(t, dir, "handlers/api/handlers_gen.go", forgeBanner+"package api\n")
	write(t, dir, "internal/handlers/api/handlers_crud_ops_gen.go", forgeBanner+"package api\n")
	write(t, dir, "mocks/api_mock_gen.go", forgeBanner+"package mocks\n")
	write(t, dir, "frontends/web/src/gen/services/api/v1/api_pb.ts", "// @generated by protoc-gen-es v2\n")
	// Hand-written code, and prose that merely mentions the marker key.
	write(t, dir, "internal/api/service.go", "package api\n")
	write(t, dir, "docs/notes.md", "files carry forge:hash=<sha256> markers\n")
}

// TestCheck_FlagsGeneratedCodeTheOldScaffoldIgnored reproduces the defect:
// a project whose .gitignore still carries the pre-fix scaffold rules has
// its generated code silently untracked. `git status --porcelain` — what
// `forge ci verify-generated` diffs with — reports NOTHING, which is why CI
// could not catch it. Check must name every ignored generated file with the
// rule that ignores it.
func TestCheck_FlagsGeneratedCodeTheOldScaffoldIgnored(t *testing.T) {
	dir := newRepo(t)
	write(t, dir, ".gitignore", preFixScaffoldGitignore)
	write(t, dir, "frontends/web/.gitignore", "node_modules/\nsrc/gen/\n") // the pre-fix frontend rule
	seedGenerated(t, dir)
	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-qm", "init")

	// The blind spot, asserted: porcelain is clean over untracked
	// generated code.
	if status := strings.TrimSpace(git(t, dir, "status", "--porcelain")); status != "" {
		t.Fatalf("fixture wrong: expected a porcelain-clean tree, got:\n%s", status)
	}

	vs, err := Check(dir)
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	got := map[string]Violation{}
	for _, v := range vs {
		if v.Rule == RuleGeneratedIgnored {
			got[v.Path] = v
		}
	}
	for _, want := range []string{
		"gen/services/api/v1/api.pb.go",
		"gen/forge_descriptor.json",
		"pkg/middleware/procedures_gen.go",
		"handlers/api/handlers_gen.go",
		"mocks/api_mock_gen.go",
		"frontends/web/src/gen/services/api/v1/api_pb.ts",
	} {
		v, ok := got[want]
		if !ok {
			t.Errorf("ignored generated file %s was not reported (got %v)", want, keys(got))
			continue
		}
		if !strings.Contains(v.Why, ".gitignore:") || !strings.Contains(v.Fix, "git add "+want) {
			t.Errorf("%s: violation must name the ignoring rule and the fix, got %+v", want, v)
		}
	}
	for _, notFlagged := range []string{
		"internal/api/service.go", // hand-written
		"docs/notes.md",           // prose mentioning the marker key
		"gen/go.mod",              // negated back in
		"internal/handlers/api/handlers_crud_ops_gen.go", // generated but tracked
	} {
		if _, ok := got[notFlagged]; ok {
			t.Errorf("%s is not ignored generated code but was reported", notFlagged)
		}
	}
	if len(got) != 6 {
		t.Errorf("want exactly the 6 ignored generated files, got %d: %v", len(got), keys(got))
	}
}

// TestCheck_CurrentScaffoldGitignoreIsClean: a project on today's scaffold
// .gitignore, with everything generated committed, has no violations — the
// check must not cry wolf on the state forge itself produces.
func TestCheck_CurrentScaffoldGitignoreIsClean(t *testing.T) {
	body, err := templates.ProjectTemplates().Get(".gitignore")
	if err != nil {
		t.Fatal(err)
	}
	fe, err := templates.FrontendTemplates().Get("nextjs/.gitignore")
	if err != nil {
		t.Fatal(err)
	}
	dir := newRepo(t)
	write(t, dir, ".gitignore", string(body))
	write(t, dir, "frontends/web/.gitignore", string(fe))
	seedGenerated(t, dir)
	// Machine-local state present on disk, correctly ignored.
	write(t, dir, ".forge-kcl/schema.k", "schema X:\n    a: int\n")
	write(t, dir, "frontends/web/public/config.js", forgeBanner+"window.__FORGE_CONFIG__ = {};\n")
	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-qm", "init")

	vs, err := Check(dir)
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	if len(vs) != 0 {
		t.Fatalf("a project on the current scaffold .gitignore must be clean, got:\n%s", Format(vs))
	}
}

// TestCheck_FlagsTrackedMachineLocalState: a committed .forge-kcl/ or dev
// config.js is reported once each, with the literal git rm --cached fix.
func TestCheck_FlagsTrackedMachineLocalState(t *testing.T) {
	dir := newRepo(t)
	write(t, dir, ".forge-kcl/schema.k", "schema X:\n    a: int\n")
	write(t, dir, ".forge-kcl/.forge-version", "v0.1.17\n")
	write(t, dir, "frontends/web/public/config.js", forgeBanner+"window.__FORGE_CONFIG__ = {};\n")
	write(t, dir, "frontends/web/public/favicon.ico", "x")
	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-qm", "init")

	vs, err := Check(dir)
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	want := map[string]string{
		".forge-kcl/":                    "git rm -r --cached .forge-kcl",
		"frontends/web/public/config.js": "git rm --cached frontends/web/public/config.js",
	}
	if len(vs) != len(want) {
		t.Fatalf("want exactly %d violations, got:\n%s", len(want), Format(vs))
	}
	for _, v := range vs {
		fix, ok := want[v.Path]
		if !ok || v.Rule != RuleLocalStateTracked || !strings.Contains(v.Fix, fix) {
			t.Errorf("unexpected violation %+v (want fix containing %q)", v, fix)
		}
	}
}

// TestCheck_OutsideAGitRepoIsSilent: no commit state, no verdict.
func TestCheck_OutsideAGitRepoIsSilent(t *testing.T) {
	dir := t.TempDir()
	seedGenerated(t, dir)
	if vs, err := Check(dir); err != nil || len(vs) != 0 {
		t.Fatalf("Check outside git = (%v, %v), want (nil, nil)", vs, err)
	}
}

func keys(m map[string]Violation) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	return out
}
