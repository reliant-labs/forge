// File: internal/generator/contract/observed.go
//
// Generates middleware_gen.go — the forge-owned observability decorator
// for a component's Service-contract interface. This REPLACES the former
// hand-written, scaffold-once observe.go: the decorator is now derived from
// the interface by the SAME ParseContract path that drives mock_gen.go, so a
// method added to the interface regenerates the wrapper automatically (zero
// hand-maintenance) and the mock and the decorator can never drift — both
// come from one parse of contract.go.
//
// The generated decorator is deliberately SLIM: one wrapper method per
// interface method, each a one-liner routing through the in-process
// observe.ComponentChain assembled in the OWNED observe_chain.go seam
// (newObserveChain). The decorator names no middleware and bakes no parameter
// (log level, sampling, which layers) — that policy lives in the owned seam
// and forge.yaml. This is the in-process twin of the Connect edge interceptor
// chain, configured the same way.
package contract

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"github.com/reliant-labs/forge/internal/checksums"
)

// observeLibImport is the forge library the decorator routes through.
const observeLibImport = "github.com/reliant-labs/forge/pkg/observe"

// observeChainSeamFunc is the owned chain-builder the generated decorator
// calls to obtain its per-package chain. Defined in observe_chain.go (the
// user-owned extension seam), same package as the decorator.
const observeChainSeamFunc = "newObserveChain"

// observedImport is one rendered import line for the decorator's import block.
// Alias is empty when the import needs no explicit alias (the path's leaf
// segment already names the package).
type observedImport struct {
	Alias string
	Path  string
}

// observedMethod is one rendered wrapper method for the decorator template.
type observedMethod struct {
	Name      string
	Signature string // parameter list, e.g. "ctx context.Context, in RunInput"
	Results   string // result list with parens when needed, e.g. "(RunResult, error)"
	Body      string // full statement body (gofmt normalizes indentation)
}

// observedData is the input to observedTmpl.
type observedData struct {
	Package     string
	Imports     []observedImport
	Iface       string
	Constructor string
	StructName  string
	SeamFunc    string
	Methods     []observedMethod
}

var observedTmpl = template.Must(template.New("observed").Parse(`// Code generated by forge. DO NOT EDIT.
// forge-owned: regenerated every run — do not edit (forge project disown to take ownership)
// Source: contract.go (the {{ .Iface }} interface) in this package.
//
// One wrapper method per {{ .Iface }} method, each routing through the
// in-process middleware chain assembled in the owned observe_chain.go
// ({{ .SeamFunc }}). Adding a method to {{ .Iface }} regenerates this file —
// there is no wrapper to maintain by hand.
package {{ .Package }}

{{ if .Imports -}}
import (
{{ range .Imports }}	{{ if .Alias }}{{ .Alias }} {{ end }}"{{ .Path }}"
{{ end }})
{{ end -}}

// {{ .Constructor }} wraps inner so every {{ .Iface }} method
// routes through the per-package observability chain (span, metrics, structured
// logging, panic-recovery) assembled by {{ .SeamFunc }} in observe_chain.go. The
// composition site emits
// {{ .Package }}.{{ .Constructor }}({{ .Package }}.New(...))
// automatically while that owned seam is present and New returns {{ .Iface }}.
func {{ .Constructor }}(inner {{ .Iface }}) {{ .Iface }} {
	return &{{ .StructName }}{inner: inner, chain: {{ .SeamFunc }}()}
}

// {{ .StructName }} decorates the inner {{ .Iface }}. It has no behavior of
// its own — every method delegates through the chain.
type {{ .StructName }} struct {
	inner {{ .Iface }}
	chain *observe.ComponentChain
}
{{ range .Methods }}
func (o *{{ $.StructName }}) {{ .Name }}({{ .Signature }}){{ if .Results }} {{ .Results }}{{ end }} {
	{{ .Body }}
}
{{ end }}`))

// WriteObservedDecorator renders middleware_gen.go for the interface named
// ifaceName in cf, wrapping every method of that interface. ctorName / structName
// are the wrapper's exported constructor and unexported struct names, resolved
// by codegen.ResolveMiddlewareWrapper (keyed off the constructor's concrete
// return type) and threaded in by the caller so the generated declaration
// matches the compose-emitted call byte-for-byte. opNamespace is the prefix for
// the per-method operation name ("<opNamespace>.<Method>") — the package name
// for a single-impl package, carrying an extra concrete-type segment when the
// package has multiple wrapped constructors.
//
// Returns (false, nil) when ifaceName is not declared in cf (nothing to wrap)
// — the caller treats that the same as "package not instrumented". When
// opts.ProjectRoot is set the write goes through the checksums chokepoint
// (Tier-1, hash-stamped, disown-aware); otherwise a raw write is used (the
// add-package stub path, adopted into the manifest on the next full generate).
func WriteObservedDecorator(cf *File, dir, ifaceName, ctorName, structName, opNamespace string, opts Options) (bool, error) {
	if ifaceName == "" {
		ifaceName = "Service"
	}
	if ctorName == "" {
		ctorName = "New" + ifaceName + "WithForgeMiddleware"
	}
	if structName == "" {
		structName = "forgeMiddleware" + ifaceName
	}
	var target *InterfaceDef
	for i := range cf.Interfaces {
		if cf.Interfaces[i].Name == ifaceName {
			target = &cf.Interfaces[i]
			break
		}
	}
	if target == nil {
		return false, nil
	}

	methods := make([]observedMethod, 0, len(target.Methods))
	for _, m := range target.Methods {
		body := renderObservedBody(m, opNamespace)
		if m.SkipObserve {
			// Method-level `// forge:no-observe`: the wrapper still exists (the
			// decorator satisfies the whole interface) but this method routes
			// AROUND the chain — a direct delegation to the inner impl.
			body = renderDirectBody(m)
		}
		methods = append(methods, observedMethod{
			Name:      m.Name,
			Signature: m.ParamSignature(),
			Results:   m.ResultSignature(),
			Body:      body,
		})
	}

	data := observedData{
		Package:     cf.Package,
		Imports:     observedImports(cf, *target),
		Iface:       ifaceName,
		Constructor: ctorName,
		StructName:  structName,
		SeamFunc:    observeChainSeamFunc,
		Methods:     methods,
	}

	var buf bytes.Buffer
	if err := observedTmpl.Execute(&buf, data); err != nil {
		return false, fmt.Errorf("execute observed template: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return false, fmt.Errorf("gofmt observed output: %w\n---\n%s", err, buf.String())
	}

	outPath := filepath.Join(dir, observedFileName())
	if opts.ProjectRoot != "" {
		rel, relErr := filepath.Rel(opts.ProjectRoot, outPath)
		if relErr != nil {
			return false, fmt.Errorf("compute project-relative decorator path: %w", relErr)
		}
		if _, werr := checksums.WriteGeneratedFile(opts.ProjectRoot, rel, formatted, opts.Checksums, true); werr != nil {
			return false, fmt.Errorf("write %s: %w", rel, werr)
		}
		return true, nil
	}
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		return false, err
	}
	return true, nil
}

// RemoveObservedDecorator deletes middleware_gen.go from dir if present —
// called when a package is NOT (or no longer) instrumented (the owned
// observe_chain.go seam is absent), so opting out by deleting the seam leaves
// no orphan decorator behind. A missing file is not an error.
func RemoveObservedDecorator(dir string) error {
	path := filepath.Join(dir, observedFileName())
	if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("remove %s: %w", path, err)
	}
	return nil
}

// observedFileName is the decorator's filename. It is a fixed name in the
// component's package dir (sibling to mock_gen.go), not package-qualified.
func observedFileName() string { return "middleware_gen.go" }

// renderDirectBody renders a wrapper method that delegates DIRECTLY to the
// inner implementation, bypassing the observe chain entirely. Used for methods
// carrying the method-level `// forge:no-observe` marker (MethodDef.SkipObserve).
// A method with results returns the inner call; a void method just invokes it.
func renderDirectBody(m MethodDef) string {
	call := fmt.Sprintf("o.inner.%s(%s)", m.Name, m.CallArgs())
	if len(m.Results) == 0 {
		return call
	}
	return "return " + call
}

// renderObservedBody renders the statement body of one wrapper method. It
// routes the inner call through the chain via observe.Around (the common
// single-value-plus-error shape) or observe.Run (error-only and every other
// shape), capturing any non-error results out of the closure. Methods without
// a context parameter run under context.Background() — metrics / recovery /
// logging still apply; there is simply no parent context to propagate.
func renderObservedBody(m MethodDef, opNamespace string) string {
	op := fmt.Sprintf("%q", opNamespace+"."+m.Name)
	inner := fmt.Sprintf("o.inner.%s(%s)", m.Name, m.CallArgs())

	outerCtx := "context.Background()"
	closureParam := "_ context.Context"
	if m.HasContext() {
		cn := m.ContextParamName()
		outerCtx = cn
		closureParam = cn + " context.Context"
	}

	results := m.Results
	switch {
	case len(results) == 1 && results[0].TypeExpr == "error":
		// error-only: one-liner through the general primitive.
		return fmt.Sprintf(
			"return observe.Run(%s, o.chain, %s, func(%s) error {\n\treturn %s\n})",
			outerCtx, op, closureParam, inner)

	case len(results) == 2 && results[1].TypeExpr == "error":
		// (T, error): the common shape — generic sugar keeps it a one-liner.
		return fmt.Sprintf(
			"return observe.Around(%s, o.chain, %s, func(%s) (%s, error) {\n\treturn %s\n})",
			outerCtx, op, closureParam, results[0].TypeExpr, inner)
	}

	// General shapes: no results, multiple non-error results, or a non-error
	// trailing result. Capture every non-error result out of the closure and
	// thread only the error (if any) through the chain.
	lastIsErr := len(results) > 0 && results[len(results)-1].TypeExpr == "error"
	nonErr := results
	if lastIsErr {
		nonErr = results[:len(results)-1]
	}

	if len(nonErr) == 0 && !lastIsErr {
		// Pure void method: no results at all.
		return fmt.Sprintf(
			"_ = observe.Run(%s, o.chain, %s, func(%s) error {\n\t%s\n\treturn nil\n})",
			outerCtx, op, closureParam, inner)
	}

	var b strings.Builder
	names := make([]string, 0, len(nonErr))
	for i, r := range nonErr {
		fmt.Fprintf(&b, "var r%d %s\n", i, r.TypeExpr)
		names = append(names, fmt.Sprintf("r%d", i))
	}

	if lastIsErr {
		fmt.Fprintf(&b, "err := observe.Run(%s, o.chain, %s, func(%s) error {\n", outerCtx, op, closureParam)
		b.WriteString("\tvar e error\n")
		fmt.Fprintf(&b, "\t%s = %s\n", strings.Join(append(append([]string{}, names...), "e"), ", "), inner)
		b.WriteString("\treturn e\n})\n")
		fmt.Fprintf(&b, "return %s, err", strings.Join(names, ", "))
		return b.String()
	}

	// One or more non-error results, no error result.
	fmt.Fprintf(&b, "_ = observe.Run(%s, o.chain, %s, func(%s) error {\n", outerCtx, op, closureParam)
	fmt.Fprintf(&b, "\t%s = %s\n", strings.Join(names, ", "), inner)
	b.WriteString("\treturn nil\n})\n")
	fmt.Fprintf(&b, "return %s", strings.Join(names, ", "))
	return b.String()
}

// observedImports assembles the decorator's import block: every package the
// wrapped interface's signatures reference (reusing collectImports, the mock
// generator's resolver), plus "context" (the wrapper bodies always take/lift a
// context) and the observe library. Deterministic order for stable codegen.
func observedImports(cf *File, iface InterfaceDef) []observedImport {
	paths := collectImports(cf, []InterfaceDef{iface})

	set := map[string]bool{}
	for _, p := range paths {
		set[p] = true
	}
	// A CHAIN-routed (non-skip) method body always references context — either
	// its own context.Context param or context.Background() for the outer call
	// / closure param. A method that carries context.Context in its signature
	// is already covered by collectImports above; the unconditional add here is
	// for a non-skip method WITHOUT a context param (context.Background()). If
	// every method is skipped (direct delegation) nothing references
	// context.Background(), so adding "context" then would be an unused import.
	for _, m := range iface.Methods {
		if !m.SkipObserve {
			set["context"] = true
			break
		}
	}
	set[observeLibImport] = true

	out := make([]observedImport, 0, len(set))
	for p := range set {
		out = append(out, observedImport{Alias: importAlias(cf, p), Path: p})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out
}

// importAlias returns the explicit alias to emit for import path p, or "" when
// the path's leaf segment already names the package (no alias needed). The
// alias is recovered from contract.go's own import block (cf.Imports maps the
// source name → path) so an aliased import in the contract carries through to
// the decorator's signatures verbatim.
func importAlias(cf *File, p string) string {
	leaf := p
	if i := strings.LastIndex(p, "/"); i >= 0 {
		leaf = p[i+1:]
	}
	for name, path := range cf.Imports {
		if path == p && name != leaf {
			return name
		}
	}
	return ""
}
