func TestObservedDecorator_Idempotent(t *testing.T) {
	dir := writeContract(t, `package checkout

import "context"

type Service interface {
	Run(ctx context.Context, in RunInput) (RunResult, error)
}

type RunInput struct{ ID string }
type RunResult struct{ OK bool }
`)
	first := genDecorator(t, dir, "Service", "checkout")
	second := genDecorator(t, dir, "Service", "checkout")
	if first != second {
		t.Errorf("decorator generation not idempotent:\n--- first ---\n%s\n--- second ---\n%s", first, second)
	}
}

func TestObservedDecorator_AddMethodRegenerates(t *testing.T) {
	// The core "no more hand-maintenance" proof at the unit level: adding a
	// method to the interface and regenerating grows the decorator's method
	// set automatically — the hand-written observe.go never did.
	dir := writeContract(t, `package checkout

import "context"

type Service interface {
	Run(ctx context.Context, in RunInput) (RunResult, error)
}

type RunInput struct{ ID string }
type RunResult struct{ OK bool }
`)
	before := genDecorator(t, dir, "Service", "checkout")
	if strings.Contains(before, "checkout.Refund") {
		t.Fatal("precondition: Refund wrapper should not exist yet")
	}

	// Add a second method and regenerate.
	if err := os.WriteFile(filepath.Join(dir, "contract.go"), []byte(`package checkout

import "context"

type Service interface {
	Run(ctx context.Context, in RunInput) (RunResult, error)
	Refund(ctx context.Context, id string) error
}

type RunInput struct{ ID string }
type RunResult struct{ OK bool }
`), 0o644); err != nil {
		t.Fatalf("rewrite contract.go: %v", err)
	}
	after := genDecorator(t, dir, "Service", "checkout")
	if !strings.Contains(after, `o.chain.Run(ctx, "checkout.Refund", func(ctx context.Context) error {`) {
		t.Errorf("regenerated decorator did not gain the Refund wrapper:\n%s", after)
	}
}

func TestObservedDecorator_NotDeclaredSkips(t *testing.T) {
	dir := writeContract(t, `package x

type Other interface{ Do() }
`)
	cf, err := ParseContract(filepath.Join(dir, "contract.go"))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	written, err := WriteObservedDecorator(cf, dir, "Service", "NewServiceWithForgeMiddleware", "forgeMiddlewareService", "x", Options{})
	if err != nil {
		t.Fatalf("WriteObservedDecorator: %v", err)
	}
	if written {
		t.Fatal("expected no decorator when the target interface is not declared")
	}
	if _, statErr := os.Stat(filepath.Join(dir, "middleware_gen.go")); statErr == nil {
		t.Fatal("no decorator file should be written when the interface is absent")
	}
}

func TestRemoveObservedDecorator(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "middleware_gen.go")
	if err := os.WriteFile(path, []byte("package checkout\n"), 0o644); err != nil {
		t.Fatalf("seed: %v", err)
	}
	if err := RemoveObservedDecorator(dir); err != nil {
		t.Fatalf("remove: %v", err)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatal("decorator file should be gone")
	}
	// Idempotent on a missing file.
	if err := RemoveObservedDecorator(dir); err != nil {
		t.Fatalf("remove (missing) should be a no-op: %v", err)
	}
}

// TestObservedDecorator_MethodLevelNoObserve: a method carrying
// `// forge:no-observe` is still wrapped by the decorator but delegates
// DIRECTLY to the inner impl (no chain), while sibling methods still route
// through chain.Around / chain.Run.
func TestObservedDecorator_MethodLevelNoObserve(t *testing.T) {
	dir := writeContract(t, `package checkout

import "context"

type Service interface {
	// Run is instrumented.
	Run(ctx context.Context, in RunInput) (RunResult, error)
	// Health is a hot-path liveness probe.
	// forge:no-observe
	Health(ctx context.Context) error
}

type RunInput struct{ ID string }
type RunResult struct{ OK bool }
`)
	got := genDecorator(t, dir, "Service", "checkout")

	// The instrumented method routes through the chain.
	if !strings.Contains(got, `o.chain.Around(ctx, "checkout.Run"`) {
		t.Fatalf("Run should route through the chain:\n%s", got)
	}
	// The skipped method delegates directly — no observe.* for Health.
	if !strings.Contains(got, "func (o *forgeMiddlewareService) Health(ctx context.Context) error {\n\treturn o.inner.Health(ctx)\n}") {
		t.Fatalf("Health should delegate directly (no chain):\n%s", got)
	}
	if strings.Contains(got, `"checkout.Health"`) {
		t.Fatalf("Health must NOT be routed through the chain:\n%s", got)
	}
}

// TestObservedDecorator_AllMethodsSkipped_NoContextImport: when every method is
// skipped and none carries a context param, the decorator must NOT import
// "context" (it would be unused → build break). observe is always imported
// (the chain field).
func TestObservedDecorator_AllMethodsSkipped_NoContextImport(t *testing.T) {
	dir := writeContract(t, `package pure

type Service interface {
	// forge:no-observe
	Compute(x int) int
	// forge:no-observe
	Name() string
}
`)
	got := genDecorator(t, dir, "Service", "pure")

	if strings.Contains(got, `"context"`) {
		t.Fatalf("all-skipped decorator must not import context:\n%s", got)
	}
	if !strings.Contains(got, `"github.com/reliant-labs/forge/pkg/observe"`) {
		t.Fatalf("decorator must still import observe (chain field):\n%s", got)
	}
	if !strings.Contains(got, "return o.inner.Compute(x)") || !strings.Contains(got, "return o.inner.Name()") {
		t.Fatalf("both methods should delegate directly:\n%s", got)
	}
}
