func taskPlanEntity() config.PlanEntity {
	return config.PlanEntity{
		Name: "Task",
		Fields: []config.PlanEntityField{
			{Name: "id", Type: "string", PrimaryKey: true},
			{Name: "title", Type: "string", NotNull: true},
		},
	}
}

func writeDBFile(t *testing.T, root, name, src string) {
	t.Helper()
	dir := filepath.Join(root, "internal", "db")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestGeneratePlanORM_RefusesANameTheProjectDeclares is reliant's measured
// case: internal/db/models.go declares `type Task = core.Task`, and the
// projection used to write task_orm_gen.go beside it, fail the validate build
// on `Task redeclared`, and revert, naming neither the declaration nor the
// way out. Now it refuses before writing, with both.
func TestGeneratePlanORM_RefusesANameTheProjectDeclares(t *testing.T) {
	root := t.TempDir()
	models := "package db\n\nimport \"example.com/app/internal/db/core\"\n\n// Task is an alias to the shared core task model.\ntype Task = core.Task\n\nfunc NewStore() {}\n"
	writeDBFile(t, root, "models.go", models)

	err := GeneratePlanORM(root, config.ORMConfig{}, []config.PlanEntity{taskPlanEntity()}, nil)
	if err == nil {
		t.Fatal("internal/db/models.go declares Task and NewStore; want a refusal")
	}
	for _, w := range []string{
		"Task, declared at internal/db/models.go:6",
		"internal/db/task_orm_gen.go for entity Task (table tasks)",
		"NewStore, declared at internal/db/models.go:8",
		"internal/db/store_gen.go for every entity",
		"`// forge:custom` above each of its declared CRUD-named rpcs (`forge project shapes --kind rpc --grep Task` lists them)",
		"rename:` in sqlc.yaml",
		"//forge:no-orm",
	} {
		if !strings.Contains(err.Error(), w) {
			t.Errorf("error does not mention %q:\n%s", w, err)
		}
	}
	if _, serr := os.Stat(filepath.Join(root, "internal", "db", "task_orm_gen.go")); serr == nil {
		t.Error("a refused projection still wrote task_orm_gen.go")
	}
	if _, serr := os.Stat(filepath.Join(root, "internal", "db", "task_repo_ext.go")); serr == nil {
		t.Error("a refused projection still scaffolded task_repo_ext.go")
	}
}

// What is NOT a collision: forge's own ORM files (this run's outputs, and a
// stale one the sweep reclaims), methods, an external test package, and names
// the ORM does not declare.
func TestGeneratePlanORM_OwnFilesAndUnrelatedNamesPass(t *testing.T) {
	root := t.TempDir()
	writeDBFile(t, root, "task_orm_gen.go", "package db\n\ntype Task struct{}\n")
	writeDBFile(t, root, "widget_orm.go", "package db\n\ntype Widget struct{}\n\nfunc NewStore() {}\n")
	writeDBFile(t, root, "repo.go", "package db\n\ntype Repo struct{}\n\nfunc (Repo) CreateTask() {}\n")
	writeDBFile(t, root, "models_test.go", "package db_test\n\ntype Task struct{}\n")
	if err := GeneratePlanORM(root, config.ORMConfig{}, []config.PlanEntity{taskPlanEntity()}, nil); err != nil {
		t.Fatalf("GeneratePlanORM: %v", err)
	}
}

// TestGeneratePlanORM_KeepsAHandWrittenTypesGo: `types.go` is the most
// ordinary file name a hand-written data layer has, and the projection used
// to delete internal/db/types.go unconditionally (it was once forge's own
// proto-era alias file). Only a forge-written one is retired now.
func TestGeneratePlanORM_KeepsAHandWrittenTypesGo(t *testing.T) {
	root := t.TempDir()
	writeDBFile(t, root, "types.go", "package db\n\n// Cursor pages the hand-written queries.\ntype Cursor string\n")
	if err := GeneratePlanORM(root, config.ORMConfig{}, []config.PlanEntity{taskPlanEntity()}, nil); err != nil {
		t.Fatalf("GeneratePlanORM: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "internal", "db", "types.go")); err != nil {
		t.Errorf("a hand-written internal/db/types.go was deleted: %v", err)
	}

	writeDBFile(t, root, "types.go", "// Code generated by forge. DO NOT EDIT.\n\npackage db\n\ntype Task = pb.Task\n")
	if err := GeneratePlanORM(root, config.ORMConfig{}, []config.PlanEntity{taskPlanEntity()}, nil); err != nil {
		t.Fatalf("GeneratePlanORM: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "internal", "db", "types.go")); err == nil {
		t.Error("forge's proto-era internal/db/types.go was not retired")
	}
}

// The advice names the rpcs the project DECLARES for the entity when the
// caller supplies them, and never the quintet the entity's name implies: on
// reliant it listed CreateMessage … ListMessages when the only unmarked one
// was MessageService.GetMessage, on a service the list did not mention.
func TestORMCollisionError_NamesDeclaredRPCs(t *testing.T) {
	root := t.TempDir()
	writeDBFile(t, root, "models.go", "package db\n\ntype Task struct{ ID string }\n")
	err := GeneratePlanORM(root, config.ORMConfig{}, []config.PlanEntity{taskPlanEntity()}, nil)
	var collision *ORMCollisionError
	if !errors.As(err, &collision) {
		t.Fatalf("want an *ORMCollisionError, got %v", err)
	}
	if got := collision.Entities(); len(got) != 1 || got[0] != "Task" {
		t.Fatalf("Entities() = %v", got)
	}
	collision.EntityRPCs = map[string][]string{"Task": {"TaskService.GetTask (proto/app/v1/task.proto:14)"}}
	msg := collision.Error()
	if !strings.Contains(msg, "above each declared rpc that makes it an entity — TaskService.GetTask (proto/app/v1/task.proto:14)") {
		t.Errorf("the advice does not name the declared rpc:\n%s", msg)
	}
	for _, hypothetical := range []string{"CreateTask", "UpdateTask", "DeleteTask", "ListTasks"} {
		if strings.Contains(msg, hypothetical) {
			t.Errorf("the advice names %s, which the project does not declare:\n%s", hypothetical, msg)
		}
	}
}
