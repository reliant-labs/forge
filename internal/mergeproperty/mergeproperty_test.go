func TestPlainMerge_IndependentChangesMergeCleanly(t *testing.T) {
	needGit(t)
	// Changes far enough apart that git needs no driver to combine them.
	base := lines(30, nil)
	ours := lines(30, map[int]string{3: "ours edit"})
	theirs := lines(30, map[int]string{27: "theirs edit"})

	got := PlainMerge(t, "gen/out.txt", base, ours, theirs)
	want := lines(30, map[int]string{3: "ours edit", 27: "theirs edit"})
	if !bytes.Equal(got, want) {
		t.Errorf("merged = %q, want both edits: %q", got, want)
	}
}

func TestPlainMerge_CreatesNestedPaths(t *testing.T) {
	needGit(t)
	base := lines(30, nil)
	got := PlainMerge(t, "a/b/c/out.txt", base, lines(30, map[int]string{2: "ours"}), lines(30, map[int]string{29: "theirs"}))
	if want := lines(30, map[int]string{2: "ours", 29: "theirs"}); !bytes.Equal(got, want) {
		t.Errorf("merged = %q, want %q", got, want)
	}
}

// A conflicting pair must fail the test and say which file conflicted: that is
// the property a generator's author is being told about.
func TestPlainMerge_AConflictFailsNamingTheFile(t *testing.T) {
	needGit(t)
	if os.Getenv("MERGEPROPERTY_CONFLICT_CHILD") == "1" {
		base := lines(3, nil)
		PlainMerge(t, "gen/conflict.txt", base, lines(3, map[int]string{2: "ours"}), lines(3, map[int]string{2: "theirs"}))
		return
	}
	cmd := exec.Command(os.Args[0], "-test.run=^TestPlainMerge_AConflictFailsNamingTheFile$")
	cmd.Env = append(os.Environ(), "MERGEPROPERTY_CONFLICT_CHILD=1")
	out, err := cmd.CombinedOutput()
	if err == nil {
		t.Fatalf("a conflicting merge passed:\n%s", out)
	}
	for _, want := range []string{"git merge", "gen/conflict.txt", "<<<<<<<"} {
		if !strings.Contains(string(out), want) {
			t.Errorf("failure output lacks %q:\n%s", want, out)
		}
	}
}

func TestAssertPlainMergeIsRenderTree(t *testing.T) {
	needGit(t)
	// One file per input, the way the scaffold ledger writes: each variant
	// adds or removes whole files, so a plain merge unions them.
	build := func(dir, variant string) {
		write := func(rel, body string) {
			p := filepath.Join(dir, "ledger", rel)
			if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := atomicfile.WriteFile(p, []byte(body), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		write("common.txt", "shared\n")
		if variant == "ours" || variant == "merged" {
			write("ours.txt", "from ours\n")
		}
		if variant == "theirs" || variant == "merged" {
			write("theirs.txt", "from theirs\n")
		}
	}
	AssertPlainMergeIsRenderTree(t, "ledger", build)
}

func TestTreeFiles(t *testing.T) {
	dir := t.TempDir()
	for rel, body := range map[string]string{"a.txt": "A", "sub/b.txt": "B", "sub/deep/c.txt": "C"} {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got := treeFiles(t, dir)
	want := map[string]string{"a.txt": "A", "sub/b.txt": "B", "sub/deep/c.txt": "C"}
	if len(got) != len(want) {
		t.Fatalf("treeFiles = %v, want %v", got, want)
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("treeFiles[%q] = %q, want %q (keys are slash-separated, relative)", k, got[k], v)
		}
	}
	if got := treeFiles(t, filepath.Join(dir, "absent")); len(got) != 0 {
		t.Errorf("a missing directory has no files, got %v", got)
	}
}

// sectioned renders a file of two independent sections, as a generator that
// certifies each part separately does; ours changes alpha, theirs omega.
func sectioned(variant string) []byte {
	part := func(name string, changed bool) string {
		state := "base"
		if changed {
			state = "changed"
		}
		return "// forge:section " + name + "\n// " + name + " is " + state + "\nvar " + name + " = \"" + state + "\"\n\n"
	}
	ours := variant == "ours" || variant == "merged"
	theirs := variant == "theirs" || variant == "merged"
	return []byte("// Code generated by forge. DO NOT EDIT.\npackage p\n\n" + part("Alpha", ours) + part("Omega", theirs))
}

func TestAssertPlainMergeIsRender(t *testing.T) {
	needGit(t)
	// A generator that aggregates independent parts keeps an unchanged line
	// between them, so two branches changing different parts merge cleanly.
	AssertPlainMergeIsRender(t, "gen/out.go", sectioned)
}

func TestAssertPlainMergeIsRender_Failures(t *testing.T) {
	needGit(t)
	if os.Getenv("MERGEPROPERTY_RENDER_CHILD") != "" {
		switch os.Getenv("MERGEPROPERTY_RENDER_CHILD") {
		case "unstampable":
			AssertPlainMergeIsRender(t, "data.bin", func(string) []byte { return []byte("x") })
		case "disagrees":
			// "merged" is not what the plain merge of ours and theirs yields.
			AssertPlainMergeIsRender(t, "gen/out.go", func(v string) []byte {
				if v == "merged" {
					return sectioned("base") // forgets that both parts changed
				}
				return sectioned(v)
			})
		}
		return
	}
	for name, want := range map[string]string{
		"unstampable": "data.bin is not stampable",
		"disagrees":   "differs from forge generate on the merged inputs",
	} {
		t.Run(name, func(t *testing.T) {
			cmd := exec.Command(os.Args[0], "-test.run=^TestAssertPlainMergeIsRender_Failures$")
			cmd.Env = append(os.Environ(), "MERGEPROPERTY_RENDER_CHILD="+name)
			out, err := cmd.CombinedOutput()
			if err == nil {
				t.Fatalf("the property held where it must not:\n%s", out)
			}
			if !strings.Contains(string(out), want) {
				t.Errorf("failure output lacks %q:\n%s", want, out)
			}
		})
	}
}
