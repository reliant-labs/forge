func needGit(t *testing.T) {
	t.Helper()
	if testing.Short() {
		t.Skip("execs git; runs in task test")
	}
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
}

func lines(n int, mark map[int]string) []byte {
	var b bytes.Buffer
	for i := 1; i <= n; i++ {
		if m, ok := mark[i]; ok {
			fmt.Fprintln(&b, m)
			continue
		}
		fmt.Fprintf(&b, "line %d\n", i)
	}
	return b.Bytes()
}

