package seedplan

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/reliant-labs/forge/pkg/schemadef"
)

// The seeder writes explicit keys: a child row's foreign key is derived from
// the parent's key at the same row index (pkLiteral), so the plan cannot
// leave a parent's key for the database to allocate. For a key a sequence
// feeds — SERIAL/BIGSERIAL, an IDENTITY, or any DEFAULT nextval(...) — that
// leaves the sequence where it was while rows 1..N now hold the values it
// would hand out next, and the app's first INSERT after a seed collides on
// the primary key. So every INSERT that writes such a column is followed by
// a statement that moves its sequence past the largest value in the table.
//
// The move is forward only: a sequence already past the seeded values (an
// earlier app insert, a START WITH above them) is left alone, as is a
// descending one.

// nextvalDefaultRE captures the sequence a `DEFAULT nextval('seq'::regclass)`
// draws from, as postgres's catalog spells that default.
var nextvalDefaultRE = regexp.MustCompile(`nextval\('((?:[^']|'')+)'(?:::regclass)?\)`)

// sequenceExpr is the SQL expression naming the sequence that feeds col of
// t, as a regclass, or "" when no sequence feeds it. A nextval DEFAULT names
// its sequence itself; an IDENTITY column's sequence is found through
// pg_get_serial_sequence, which reads the column's dependency.
func sequenceExpr(t schemadef.Table, col schemadef.Column) string {
	if col.Type != schemadef.TypeInt || col.IsArray || col.IsGenerated {
		return ""
	}
	if m := nextvalDefaultRE.FindStringSubmatch(col.Default); m != nil {
		return sqlString(strings.ReplaceAll(m[1], "''", "'")) + "::regclass"
	}
	if col.IsIdentity {
		return fmt.Sprintf("pg_get_serial_sequence(%s, %s)::regclass", sqlString(QualifiedTable(t)), sqlString(col.Name))
	}
	return ""
}

// sequenceSync is the statement that advances every sequence feeding a
// column tp's INSERT writes past the largest value now in the table, or ""
// when the INSERT writes none.
func (p *Plan) sequenceSync(tp tablePlan) string {
	if tp.n == 0 {
		return ""
	}
	var b strings.Builder
	for _, cp := range tp.cols {
		if cp.omit {
			continue
		}
		seq := sequenceExpr(tp.table, cp.col)
		if seq == "" {
			continue
		}
		fmt.Fprintf(&b, `SELECT setval(s.seq, s.hi) FROM (
    SELECT q.seq, (SELECT max(%s) FROM %s) AS hi,
           COALESCE(pg_sequence_last_value(q.seq) + ps.seqincrement, ps.seqstart) AS next,
           ps.seqincrement AS step
    FROM (SELECT %s AS seq) q JOIN pg_sequence ps ON ps.seqrelid = q.seq
) s WHERE s.step > 0 AND s.hi >= s.next;
`, quoteIdent(cp.col.Name), QualifiedTable(tp.table), seq)
	}
	return b.String()
}

// writesIdentity reports whether tp's INSERT names an IDENTITY column. Such
// an INSERT carries OVERRIDING SYSTEM VALUE: a GENERATED ALWAYS identity
// refuses an explicit value without it, and for GENERATED BY DEFAULT the
// clause changes nothing.
func writesIdentity(tp tablePlan) bool {
	for _, cp := range tp.cols {
		if !cp.omit && cp.col.IsIdentity && !cp.col.IsGenerated {
			return true
		}
	}
	return false
}
